// Package blocklist holds the embedded list of common passwords access refuses,
// generated from SecLists by "go generate ./internal/blocklist", and the fold
// the password-context and common-password checks share.
package blocklist

import (
	"crypto/sha256"
	_ "embed" // go:embed of common.txt
	"encoding/hex"
	"errors"
	"fmt"
	"slices"
	"strconv"
	"strings"
	"sync"

	"golang.org/x/text/cases"
	"golang.org/x/text/unicode/norm"
)

//go:embed common.txt
var common string

// Fold returns s in the form the list holds and the password-context and
// common-password checks compare: NFC, then full Unicode case folding.
func Fold(s string) string {
	return cases.Fold().String(norm.NFC.String(s))
}

// Contains reports whether password, folded, is on the embedded list.
func Contains(password string) bool {
	_, found := slices.BinarySearch(sortedEntries(), Fold(password))
	return found
}

// A package-level sync.OnceValue is built by the package's init, which
// links common.txt into every binary importing access; sync.Once leaves it out
// of one that never calls Contains.
var (
	loadOnce sync.Once
	sorted   []string
)

// sortedEntries panics on a malformed common.txt; TestBlocklistInSync keeps
// the embedded file decodable.
func sortedEntries() []string {
	loadOnce.Do(func() {
		_, entries, err := Decode(common)
		if err != nil {
			panic(err)
		}
		slices.Sort(entries)
		sorted = entries
	})
	return sorted
}

// Header is common.txt's provenance.
type Header struct {
	URL           string // the source file at Commit
	Commit        string
	SourceSHA256  string
	BodySHA256    string // of every byte after the header's blank line
	MinRunes      int    // the shortest entry kept, in runes after Fold
	SourceEntries int    // non-empty lines in the source
	Survivors     int    // distinct folded entries of at least MinRunes
	Kept          int    // the first Survivors in the source's order, capped
}

const (
	keyURL           = "url"
	keyCommit        = "commit"
	keyMinRunes      = "min-runes"
	keySourceEntries = "source-entries"
	keySurvivors     = "survivors"
	keyKept          = "kept"
	keySourceSHA256  = "source-sha256"
	keyBodySHA256    = "body-sha256"
)

// Encode renders h, with Kept and BodySHA256 taken from entries, a blank
// line, then one entry per line. Every entry must be non-empty and hold no
// newline, or Decode refuses the result.
func Encode(h *Header, entries []string) []byte {
	body := strings.Join(entries, "\n") + "\n"
	sum := sha256.Sum256([]byte(body))
	var b strings.Builder
	b.WriteString("# Code generated by \"go generate ./internal/blocklist\"; DO NOT EDIT.\n")
	b.WriteString("# Common passwords from SecLists (MIT, LICENSE.SecLists), folded, in the source's frequency order.\n")
	for _, kv := range [][2]string{
		{keyURL, h.URL},
		{keyCommit, h.Commit},
		{keyMinRunes, strconv.Itoa(h.MinRunes)},
		{keySourceEntries, strconv.Itoa(h.SourceEntries)},
		{keySurvivors, strconv.Itoa(h.Survivors)},
		{keyKept, strconv.Itoa(len(entries))},
		{keySourceSHA256, h.SourceSHA256},
		{keyBodySHA256, hex.EncodeToString(sum[:])},
	} {
		fmt.Fprintf(&b, "# %s: %s\n", kv[0], kv[1])
	}
	b.WriteString("\n")
	b.WriteString(body)
	return []byte(b.String())
}

// Decode parses Encode's output. It refuses a malformed header or one
// missing a field, a body whose hash or entry count differs from the header,
// an empty body or entry, and a body without its final newline.
func Decode(data string) (Header, []string, error) {
	head, body, ok := strings.Cut(data, "\n\n")
	if !ok {
		return Header{}, nil, errors.New("blocklist: no blank line ends the header")
	}
	h, err := decodeHeader(head)
	if err != nil {
		return Header{}, nil, err
	}
	sum := sha256.Sum256([]byte(body))
	if hex.EncodeToString(sum[:]) != h.BodySHA256 {
		return Header{}, nil, errors.New("blocklist: the body does not match the header's body-sha256")
	}
	if !strings.HasSuffix(body, "\n") {
		return Header{}, nil, errors.New("blocklist: the body is empty or lacks its final newline")
	}
	entries := strings.Split(strings.TrimSuffix(body, "\n"), "\n")
	if slices.Contains(entries, "") {
		return Header{}, nil, errors.New("blocklist: the body holds an empty entry")
	}
	if len(entries) != h.Kept {
		return Header{}, nil, fmt.Errorf("blocklist: the body holds %d entries, the header says %d", len(entries), h.Kept)
	}
	return h, entries, nil
}

func decodeHeader(head string) (Header, error) {
	fields := map[string]string{}
	for line := range strings.SplitSeq(head, "\n") {
		if !strings.HasPrefix(line, "# ") {
			return Header{}, fmt.Errorf("blocklist: header line %q is not a comment", line)
		}
		if k, v, ok := strings.Cut(line[2:], ": "); ok {
			fields[k] = v
		}
	}
	h := Header{URL: fields[keyURL], Commit: fields[keyCommit], SourceSHA256: fields[keySourceSHA256], BodySHA256: fields[keyBodySHA256]}
	if slices.Contains([]string{h.URL, h.Commit, h.SourceSHA256, h.BodySHA256}, "") {
		return Header{}, errors.New("blocklist: the header is missing a field")
	}
	for _, f := range []struct {
		dst *int
		key string
	}{{&h.MinRunes, keyMinRunes}, {&h.SourceEntries, keySourceEntries}, {&h.Survivors, keySurvivors}, {&h.Kept, keyKept}} {
		n, err := strconv.Atoi(fields[f.key])
		if err != nil {
			return Header{}, fmt.Errorf("blocklist: header %s: %w", f.key, err)
		}
		*f.dst = n
	}
	return h, nil
}
