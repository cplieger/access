// CVE-2017-15361: the fingerprint is the detector's, prime for prime and
// residue for residue.
func TestROCAFingerprint_Reference(t *testing.T) {
	t.Parallel()
	if !slices.Equal(rocaPrimes[:], rocaRefPrimes) {
		t.Fatalf("primes %v; the detector checks %v", rocaPrimes, rocaRefPrimes)
	}
	for i, p := range rocaRefPrimes {
		mask, ok := new(big.Int).SetString(rocaRefPrints[i], 10)
		if !ok {
			t.Fatalf("print %d does not parse", i)
		}
		for r := range p {
			if got, want := generatedBy65537(r, p), mask.Bit(int(r)) == 1; got != want {
				t.Errorf("residue %d mod %d: generated %v; the detector says %v", r, p, got, want)
			}
		}
	}
}
